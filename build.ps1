# Builds Velox.exe (and the small wallpaper helper app built into it) and installs it into
# %USERPROFILE%\Tools\Velox.
#
#   powershell -ExecutionPolicy Bypass -File gaming-phone\build.ps1 [-Out <folder>]
#
# The version comes from gaming-phone\VERSION. The address checked for updates comes from
# gaming-phone\update-url.txt (no file: this build never checks). The public update key is
# gaming-phone\src\update_key.h, made by release\new-signing-key.ps1.
param([string]$Out = "$env:USERPROFILE\Tools\Velox", [string]$HelperKeystore = '', [string]$HelperPasswordFile = '')
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
if ([bool]$HelperKeystore -ne [bool]$HelperPasswordFile) { throw 'Supply both -HelperKeystore and -HelperPasswordFile.' }
if ($HelperKeystore) {
    $HelperKeystore = (Resolve-Path -LiteralPath $HelperKeystore).Path
    $HelperPasswordFile = (Resolve-Path -LiteralPath $HelperPasswordFile).Path
}
$gcc = if ($env:MINGW_HOME) { Join-Path $env:MINGW_HOME 'bin' } else { "$env:USERPROFILE\Tools\mingw64\bin" }
$env:PATH = "$gcc;$env:PATH"
$Out = [IO.Path]::GetFullPath($Out)
$build = Join-Path $root 'build'
New-Item -ItemType Directory -Force $build, $Out | Out-Null

function Run($exe) {
    & $exe @args
    if ($LASTEXITCODE -ne 0) { throw "$([IO.Path]::GetFileName($exe)) failed (exit $LASTEXITCODE)" }
}

# ---- version and update settings
$version = (Get-Content "$root\VERSION" -Raw).Trim()
if ($version -notmatch '^(\d+)\.(\d+)\.(\d+)$') { throw "VERSION must look like 1.2.3, not '$version'" }
$major, $minor, $patch = $Matches[1], $Matches[2], $Matches[3]
Set-Content -Path "$build\version.h" -Encoding Ascii -Value @"
// Generated by build.ps1 from gaming-phone\VERSION.
#pragma once
#define GP_VERSION_MAJOR $major
#define GP_VERSION_MINOR $minor
#define GP_VERSION_PATCH $patch
#define GP_VERSION_STRING "$version"
#define GP_VERSION_WSTRING L"$version"
"@
$url = if (Test-Path "$root\update-url.txt") { (Get-Content "$root\update-url.txt" -Raw).Trim() } else { '' }
if ($url -and $url -notmatch '^https://') { throw 'update-url.txt must hold an https:// address' }
Set-Content -Path "$build\update_config.h" -Encoding Ascii -Value @"
// Generated by build.ps1 from gaming-phone\update-url.txt.
#pragma once
#define GP_UPDATE_URL L"$url"
"@
if (-not (Test-Path "$root\src\update_key.h")) {
    Set-Content -Path "$build\update_key.h" -Encoding Ascii -Value @"
// No signing key yet (run release\new-signing-key.ps1), so this build can't take updates.
#pragma once
static const unsigned char kUpdatePublicKey[] = {0};
static const unsigned long kUpdatePublicKeySize = 0;
"@
} elseif (Test-Path "$build\update_key.h") { Remove-Item "$build\update_key.h" }

# ---- icon
$iconSrc = Get-Item "$root\tools\VeloxIcon.java"
if (-not (Test-Path "$build\velox.ico") -or $iconSrc.LastWriteTime -gt (Get-Item "$build\velox.ico").LastWriteTime) {
    Run java $iconSrc.FullName "$build\velox.ico"
}

# ---- helper app (sets wallpapers inside the phone)
$helperApk = "$build\helper.apk"
$helperSrc = Get-ChildItem "$root\helper" -Recurse -File
$stale = $HelperKeystore -or -not (Test-Path $helperApk) -or ($helperSrc | Where-Object { $_.LastWriteTime -gt (Get-Item $helperApk).LastWriteTime })
if ($stale) {
    $sdk = @("$env:LOCALAPPDATA\Android\Sdk", $env:ANDROID_SDK_ROOT, $env:ANDROID_HOME) | Where-Object { $_ -and (Test-Path "$_\build-tools") } | Select-Object -First 1
    if (-not $sdk) { throw 'The Android SDK (build-tools and platforms) is needed to build the helper app.' }
    $bt = Get-ChildItem "$sdk\build-tools" -Directory | Sort-Object { [version]($_.Name -replace '-.*$', '') } -Descending | Select-Object -First 1
    $androidJar = (Get-ChildItem "$sdk\platforms" -Directory | Sort-Object Name -Descending | Select-Object -First 1).FullName + '\android.jar'
    $javaBin = if ($env:JAVA_HOME) { Join-Path $env:JAVA_HOME 'bin' } else { Split-Path (Get-Command javac).Source }
    $h = "$build\helper"
    if (Test-Path $h) { Remove-Item -Recurse -Force $h }
    New-Item -ItemType Directory -Force "$h\classes", "$h\dex" | Out-Null
    $sources = Get-ChildItem "$root\helper\src" -Recurse -Filter *.java | ForEach-Object FullName
    # Passed as one array: PowerShell would otherwise treat -classpath/-d as its own parameters.
    $javacArgs = @('--release', '11', '-encoding', 'UTF-8', '-Xlint:-options', '-classpath', $androidJar, '-d', "$h\classes") + @($sources)
    Run "$javaBin\javac.exe" @javacArgs
    Push-Location "$h\classes"
    try { Run "$javaBin\jar.exe" cf "$h\classes.jar" . } finally { Pop-Location }
    Run "$($bt.FullName)\d8.bat" --release --min-api 30 --lib "$androidJar" --output "$h\dex" "$h\classes.jar"
    $aaptArgs = @('link', '-o', "$h\base.apk", '-I', $androidJar, '--manifest', "$root\helper\AndroidManifest.xml",
        '--min-sdk-version', '30', '--target-sdk-version', '35')
    Run "$($bt.FullName)\aapt2.exe" @aaptArgs
    Push-Location "$h\dex"
    try { Run "$javaBin\jar.exe" uf "$h\base.apk" classes.dex } finally { Pop-Location }
    Run "$($bt.FullName)\zipalign.exe" -p -f 4 "$h\base.apk" "$h\aligned.apk"
    $keys = Join-Path $root 'keys'
    $ks = if ($HelperKeystore) { $HelperKeystore } else { "$keys\helper.keystore" }
    $passwordFile = if ($HelperPasswordFile) { $HelperPasswordFile } else { "$keys\helper.pass" }
    New-Item -ItemType Directory -Force $keys | Out-Null
    if (-not (Test-Path $ks)) {
        $pass = -join ((48..57) + (65..90) + (97..122) | Get-Random -Count 24 | ForEach-Object { [char]$_ })
        Set-Content -Path "$keys\helper.pass" -Value $pass -NoNewline -Encoding Ascii
        Run "$javaBin\keytool.exe" @('-genkeypair', '-keystore', $ks, '-alias', 'helper', '-keyalg', 'RSA',
            '-keysize', '2048', '-validity', '10000', '-storepass:file', $passwordFile,
            '-keypass:file', $passwordFile, '-dname', 'CN=Velox Helper')
    }
    Run "$($bt.FullName)\apksigner.bat" sign --ks $ks --ks-key-alias helper --ks-pass "file:$passwordFile" --out $helperApk "$h\aligned.apk"
    Remove-Item -Recurse -Force $h
    if (Test-Path "$helperApk.idsig") { Remove-Item "$helperApk.idsig" }
}

# ---- Android home, settings and the private desktop bridge
$companionSdk = @($env:ANDROID_SDK_ROOT, $env:ANDROID_HOME, "$env:LOCALAPPDATA\Android\Sdk") | Where-Object { $_ -and (Test-Path "$_\build-tools") } | Select-Object -First 1
& "$root\companion\build.ps1" -Sdk $companionSdk -HelperKeystore $HelperKeystore -HelperPasswordFile $HelperPasswordFile

# ---- the launcher
$manifestOverride = Join-Path $build 'manifest'
New-Item -ItemType Directory -Force $manifestOverride | Out-Null
[IO.File]::WriteAllText("$manifestOverride\empty.cpp", '// The application manifest is provided by app.rc, not the toolchain default.')
Run "$gcc\g++.exe" -c "$manifestOverride\empty.cpp" -o "$manifestOverride\default-manifest.o"
# GCC 16 adds default-manifest.o unconditionally. Override just that startup object
# locally so the linker receives one manifest; never modify the shared toolchain.
$guard = [IO.File]::ReadAllText("$root\navigation\post-fs-data.sh").Replace("`r", '')
[IO.File]::WriteAllText("$build\nav-guard.sh", $guard, (New-Object System.Text.UTF8Encoding($false)))
Push-Location "$root\src"
$resArgs = @('-I', '..\build', 'app.rc', '-O', 'coff', '-o', "$build\app.res")
try { Run "$gcc\windres.exe" @resArgs } finally { Pop-Location }
$sources = 'main', 'phone', 'art', 'overlay', 'net', 'setup', 'update', 'sysmon', 'experience', 'playtools', 'controllers', 'presets', 'vault', 'studio', 'instances', 'localization' | ForEach-Object { "$root\src\$_.cpp" }
$exe = Join-Path $Out 'Velox.exe'
$gccArgs = @('-B', 'build/manifest/', ('-ffile-prefix-map=' + $root + '=.'), ('-ffile-prefix-map=' + $root.Replace('\','/') + '=.'),
    '-std=c++20', '-O2', '-s', '-static', '-municode', '-mwindows', '-Wall', '-I', $build, '-I', "$root\src") + $sources +
    @("$build\app.res", '-o', $exe, '-lgdiplus', '-lcomdlg32', '-ldwmapi', '-lshell32', '-lshlwapi', '-lole32', '-luuid', '-luxtheme',
      '-lwinhttp', '-lbcrypt', '-ldxgi', '-lcomctl32', '-lpdh','-lwbemuuid','-loleaut32', '-lwintrust', '-lcrypt32', '-ldinput8', '-ldxguid', '-lws2_32', '-liphlpapi')
# Keep the startup-object prefix relative: GCC's endfile specs don't quote spaces.
Push-Location $root
try { Run "$gcc\g++.exe" @gccArgs } finally { Pop-Location }
# Keep shipped art beside every build; personal pictures and settings live in data instead.
$wallpapers = Join-Path $root 'wallpapers'
if (Test-Path $wallpapers) {
    New-Item -ItemType Directory -Force "$Out\wallpapers" | Out-Null
    Get-ChildItem -LiteralPath $wallpapers -File | Where-Object { $_.Extension -in '.png', '.jpg', '.jpeg' } |
        Copy-Item -Destination "$Out\wallpapers"
}
Write-Host "Done: $exe ($version)"
