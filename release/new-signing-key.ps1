# Creates the key pair that signs Velox's update manifests. Run it once.
#
#   powershell -ExecutionPolicy Bypass -File gaming-phone\release\new-signing-key.ps1
#
# The private key goes to gaming-phone\keys\update-signing.key. Keep it secret and back it up:
# anyone who has it can push updates to every copy, and if it's lost, copies already out there
# can't be updated any more. The public half goes into gaming-phone\src\update_key.h.
param([switch]$Force)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
$keyFile = Join-Path $root 'keys\update-signing.key'
$header = Join-Path $root 'src\update_key.h'
if ((Test-Path $keyFile) -and -not $Force) {
    throw "$keyFile already exists. Use -Force only if you really want a new key: copies built with the old one stop accepting updates."
}
$params = New-Object System.Security.Cryptography.CngKeyCreationParameters
$params.ExportPolicy = [System.Security.Cryptography.CngExportPolicies]::AllowPlaintextExport
$key = [System.Security.Cryptography.CngKey]::Create([System.Security.Cryptography.CngAlgorithm]::ECDsaP256, [NullString]::Value, $params)
$private = $key.Export([System.Security.Cryptography.CngKeyBlobFormat]::EccPrivateBlob)
$public = $key.Export([System.Security.Cryptography.CngKeyBlobFormat]::EccPublicBlob)
$key.Dispose()
New-Item -ItemType Directory -Force (Split-Path $keyFile) | Out-Null
[IO.File]::WriteAllBytes($keyFile, $private)
$lines = for ($i = 0; $i -lt $public.Length; $i += 12) {
    '    ' + (($public[$i..([Math]::Min($i + 11, $public.Length - 1))] | ForEach-Object { '0x{0:x2}' -f $_ }) -join ', ') + ','
}
Set-Content -Path $header -Encoding Ascii -Value @"
// Public key that update manifests must be signed with (ECDSA P-256, as a BCRYPT_ECCPUBLIC_BLOB).
// Generated by gaming-phone/release/new-signing-key.ps1. The matching private key is
// gaming-phone/keys/update-signing.key, which must never be shipped or shared.
#pragma once

static const unsigned char kUpdatePublicKey[] = {
$($lines -join "`r`n")
};
static const unsigned long kUpdatePublicKeySize = $($public.Length);
"@
Write-Host "Private key: $keyFile  (back it up, keep it secret)"
Write-Host "Public key:  $header"
